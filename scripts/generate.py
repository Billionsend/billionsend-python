class TypeGen:
    def __init__(self, spec: dict[str, Any]) -> None:
        self.spec = spec
        self.schemas: dict[str, Any] = spec["components"]["schemas"]
        self.blocks: list[str] = []
        self.names: set[str] = set()
        self.done: set[str] = set()
        self.exported: list[str] = []
        self.uses_any = False
        self.memo: dict[int, str] = {}

    def unique(self, name: str) -> str:
        candidate, n = name, 2
        while candidate in self.names or candidate in self.schemas:
            candidate = f"{name}{n}"
            n += 1
        self.names.add(candidate)
        return candidate

    def component(self, name: str) -> str:
        if name in self.done:
            return name
        self.done.add(name)
        self.names.add(name)
        if name in SCHEMA_OVERRIDES:
            target = SCHEMA_OVERRIDES[name]
            for ref in re.findall(r"[A-Z]\w+", target):
                if ref in self.schemas:
                    self.component(ref)
            self.blocks.append(f"{name}: TypeAlias = {target}")
            self.exported.append(name)
            return name
        self.named(name, self.schemas[name], fixed=True)
        return name

    def named(self, name: str, schema: dict[str, Any], *, fixed: bool = False) -> str:
        """Emit ``schema`` under ``name`` (a TypedDict or an alias) and return the name."""
        if not fixed:
            name = self.unique(name)
        if self.is_object(schema) and schema.get("properties"):
            self.memo[id(schema)] = name
            self.typed_dict(name, schema)
        else:
            expr = self.annotation(schema, name)
            lines = [f"{name}: TypeAlias = {expr}"]
            if schema.get("description"):
                lines += docstring(schema["description"], "")
            self.blocks.append("\n".join(lines))
        self.exported.append(name)
        return name

    @staticmethod
    def types_of(schema: dict[str, Any]) -> list[str]:
        t = schema.get("type")
        if t is None:
            return []
        return list(t) if isinstance(t, list) else [t]

    def is_object(self, schema: dict[str, Any]) -> bool:
        types = self.types_of(schema)
        return "object" in types or (not types and "properties" in schema)

    def typed_dict(self, name: str, schema: dict[str, Any]) -> None:
        required = set(schema.get("required", []))
        fields: list[tuple[str, str]] = []
        for prop, sub in schema["properties"].items():
            ann = self.annotation(sub, name + pascal(prop))
            fields.append((prop, ann if prop in required else f"NotRequired[{ann}]"))
        functional = any(not p.isidentifier() or keyword.iskeyword(p) for p, _ in fields)
        lines: list[str] = []
        if functional:
            if schema.get("description"):
                lines += [f"# {line}" for line in textwrap.wrap(schema["description"], 96)]
            lines.append(f'{name} = TypedDict("{name}", {{')
            lines += [f'    "{p}": {a},' for p, a in fields]
            lines.append("})")
        else:
            lines.append(f"class {name}(TypedDict):")
            lines += docstring(schema.get("description", ""), "    ")
            lines += [f"    {p}: {a}" for p, a in fields]
            if not fields:
                lines.append("    pass")
        self.blocks.append("\n".join(lines))

    def variant_names(self, variants: list[dict[str, Any]], base: str) -> list[str]:
        objects = [self.resolve(v) for v in variants]
        if all(self.is_object(o) and o.get("properties") for o in objects):
            common = set.intersection(*(set(o["properties"]) for o in objects))
            for prop in sorted(common):
                values = [o["properties"][prop].get("enum") for o in objects]
                if all(v and len(v) == 1 and isinstance(v[0], str) for v in values):
                    tags = [pascal(v[0]) for v in values if v]
                    if len(set(tags)) == len(tags):
                        return [base + t for t in tags]
        return [f"{base}{i + 1}" for i in range(len(variants))]

    def resolve(self, schema: dict[str, Any]) -> dict[str, Any]:
        while "$ref" in schema:
            schema = self.schemas[schema["$ref"].rsplit("/", 1)[1]]
        return schema

    def annotation(self, schema: dict[str, Any], hint: str) -> str:
        if not schema:
            self.uses_any = True
            return "Any"
        if "$ref" in schema:
            return self.component(schema["$ref"].rsplit("/", 1)[1])
        if "anyOf" in schema or "oneOf" in schema:
            variants = schema.get("anyOf") or schema["oneOf"]
            names = self.variant_names(variants, hint)
            parts: list[str] = []
            for sub, sub_name in zip(variants, names, strict=True):
                ann = self.annotation(sub, sub_name)
                for piece in ann.split(" | "):
                    if piece not in parts:
                        parts.append(piece)
            if "None" in parts:
                parts.remove("None")
                parts.append("None")
            return " | ".join(parts)
        types = self.types_of(schema)
        nullable = "null" in types
        types = [t for t in types if t != "null"]
        if "enum" in schema:
            values = schema["enum"]
            literal = [repr(v) for v in values if v is not None]
            nullable = nullable or None in values
            expr = f"Literal[{', '.join(literal)}]" if literal else "None"
            return f"{expr} | None" if nullable and literal else expr
        if not types:
            types = ["object"] if "properties" in schema else []
        if not types and nullable:
            return "None"
        if not types:
            self.uses_any = True
            return "Any | None" if nullable else "Any"
        parts = [self.single(t, schema, hint) for t in types]
        if nullable:
            parts.append("None")
        return " | ".join(parts)

    def single(self, kind: str, schema: dict[str, Any], hint: str) -> str:
        if kind == "string":
            return "str"
        if kind == "integer":
            return "int"
        if kind == "number":
            return "float"
        if kind == "boolean":
            return "bool"
        if kind == "array":
            return f"list[{self.annotation(schema.get('items', {}), hint + 'Item')}]"
        if kind == "object":
            if schema.get("properties"):
                if id(schema) in self.memo:
                    return self.memo[id(schema)]
                name = self.unique(hint)
                self.memo[id(schema)] = name
                self.typed_dict(name, schema)
                self.exported.append(name)
                return name
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                return f"dict[str, {self.annotation(extra, hint + 'Value')}]"
            self.uses_any = True
            return "dict[str, Any]"
        raise ValueError(f"unsupported schema type {kind!r} at {hint}")

    def render(self) -> str:
        imports = ["Literal", "NotRequired", "TypeAlias", "TypedDict"]
        if self.uses_any:
            imports.insert(0, "Any")
        out = [
            HEADER,
            '"""Request and response types of the BillionSend API.\n\n'
            "Every type is a ``TypedDict`` (or an alias of one): responses are plain ``dict``\n"
            'objects and request parameters are written as ``dict`` literals."""\n',
            "from __future__ import annotations\n",
            f"from typing import {', '.join(imports)}\n",
            "__all__ = [" + ", ".join(f'"{n}"' for n in sorted(set(self.exported))) + "]\n",
        ]
        out += [block + "\n" for block in self.blocks]
        return "\n\n".join(out)


