def pascal(text: str) -> str:
    parts = re.split(r"[^0-9a-zA-Z]+", text)
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    return out if out and not out[0].isdigit() else "V" + out


def snake(text: str) -> str:
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", text)
    text = re.sub(r"[^0-9a-zA-Z]+", "_", text).strip("_").lower()
    return text + "_" if keyword.iskeyword(text) else text


def pyname(text: str) -> str:
    name = snake(text)
    return name + "_" if keyword.iskeyword(name) or name in RESERVED_KWARGS else name


def docstring(text: str, indent: str) -> list[str]:
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').strip()
    if not text:
        return []
    paragraphs = [textwrap.fill(p, width=88 - len(indent)) for p in text.split("\n\n")]
    body = "\n\n".join(paragraphs).splitlines()
    if len(body) == 1 and len(body[0]) + len(indent) + 6 <= 100:
        return [f'{indent}"""{body[0]}"""']
    lines = [f'{indent}"""{body[0]}']
    lines += [f"{indent}{line}" if line else "" for line in body[1:]]
    lines.append(f'{indent}"""')
    return lines


