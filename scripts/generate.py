def generate() -> dict[Path, str]:
    spec = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    types = TypeGen(spec)
    ops = build_operations(spec, types)
    type_names = set(types.exported) | types.names
    return {
        TYPES_OUT: types.render(),
        SYNC_OUT: render_resources(ops, False, type_names),
        ASYNC_OUT: render_resources(ops, True, type_names),
    }


def ruff(paths: list[Path]) -> None:
    args = [str(p) for p in paths]
    ruff_cmd = [sys.executable, "-m", "ruff"]
    subprocess.run([*ruff_cmd, "check", "--fix-only", "--quiet", *args], check=True)  # noqa: S603
    subprocess.run([*ruff_cmd, "format", "--quiet", *args], check=True)  # noqa: S603


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the SDK's types and resources.")
    parser.add_argument(
        "--check", action="store_true", help="fail if the generated files are stale"
    )
    args = parser.parse_args(argv)

    outputs = generate()
    before = {t: t.read_text(encoding="utf-8") if t.exists() else None for t in outputs}
    for target, text in outputs.items():
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    ruff(list(outputs))
    ruff(list(outputs))
    if args.check:
        stale = [t for t in outputs if t.read_text(encoding="utf-8") != before[t]]
        for target, original in before.items():
            if original is None:
                target.unlink()
            else:
                target.write_text(original, encoding="utf-8")
        if stale:
            names = ", ".join(str(t.relative_to(ROOT)) for t in stale)
            print(f"generated files are stale, run `python scripts/generate.py`: {names}")
            return 1
        print("generated files match the snapshot")
        return 0
    print("wrote " + ", ".join(str(t.relative_to(ROOT)) for t in outputs))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
