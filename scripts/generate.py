import json
import keyword
import re
import subprocess
import sys
import textwrap
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "openapi" / "api.openapi.json"
PACKAGE = ROOT / "src" / "billionsend"
TYPES_OUT = PACKAGE / "types.py"
SYNC_OUT = PACKAGE / "resources" / "_sync.py"
ASYNC_OUT = PACKAGE / "resources" / "_async.py"

HEADER = "# Generated by scripts/generate.py from openapi/api.openapi.json. Do not edit.\n"

# A file in a multipart form (a schema string with ``format: binary``).
FILE_UPLOAD = """FileUpload: TypeAlias = (
    bytes
    | IO[bytes]
    | tuple[str, bytes | IO[bytes]]
    | tuple[str, bytes | IO[bytes], str]
)
\"\"\"A file to upload: its content (``bytes`` or a binary file object), or a tuple of the
file name and content, optionally followed by the content type.\"\"\"
"""

# A multipart text field the API reads as JSON (its description starts with "JSON-encoded").
JSON_TEXT = """JsonText: TypeAlias = str | dict[str, Any] | list[Any]
\"\"\"A JSON-encoded field of a multipart form: a ``str`` is sent as it is, a ``dict`` or
``list`` is encoded with ``json.dumps``.\"\"\"
"""

# Header parameters -> keyword argument names.
HEADER_KWARGS = {"x-batch-validation": "batch_validation"}

# Taken as the ``idempotency_key`` keyword of every operation that declares it.
IDEMPOTENCY_KEY_HEADER = "idempotency-key"

HTTP_METHODS = ("get", "put", "post", "patch", "delete")
RESERVED_KWARGS = {"params", "extra_headers", "timeout", "idempotency_key", "self"}


def pascal(text: str) -> str:
    parts = re.split(r"[^0-9a-zA-Z]+", text)
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    return out if out and not out[0].isdigit() else "V" + out


def snake(text: str) -> str:
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", text)
    text = re.sub(r"[^0-9a-zA-Z]+", "_", text).strip("_").lower()
    return text + "_" if keyword.iskeyword(text) else text


def pyname(text: str) -> str:
    name = snake(text)
    return name + "_" if keyword.iskeyword(name) or name in RESERVED_KWARGS else name


def docstring(text: str, indent: str) -> list[str]:
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').strip()
    if not text:
        return []
    paragraphs = [textwrap.fill(p, width=88 - len(indent)) for p in text.split("\n\n")]
    body = "\n\n".join(paragraphs).splitlines()
    if len(body) == 1 and len(body[0]) + len(indent) + 6 <= 100:
        return [f'{indent}"""{body[0]}"""']
    lines = [f'{indent}"""{body[0]}']
    lines += [f"{indent}{line}" if line else "" for line in body[1:]]
    lines.append(f'{indent}"""')
    return lines


