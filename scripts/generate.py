class TypeGen:
    def __init__(self, spec: dict[str, Any]) -> None:
        self.spec = spec
        self.schemas: dict[str, Any] = spec["components"]["schemas"]
        self.blocks: list[str] = []
        self.names: set[str] = set()
        self.done: set[str] = set()
        self.exported: list[str] = []
        self.uses_any = False
        self.memo: dict[int, str] = {}

    def unique(self, name: str) -> str:
        candidate, n = name, 2
        while candidate in self.names or candidate in self.schemas:
            candidate = f"{name}{n}"
            n += 1
        self.names.add(candidate)
        return candidate

    def component(self, name: str) -> str:
        if name in self.done:
            return name
        self.done.add(name)
        self.names.add(name)
        self.named(name, self.schemas[name], fixed=True)
        return name

    def named(self, name: str, schema: dict[str, Any], *, fixed: bool = False) -> str:
        """Emit ``schema`` under ``name`` (a TypedDict or an alias) and return the name."""
        if not fixed:
            name = self.unique(name)
        if self.is_object(schema) and schema.get("properties"):
            self.memo[id(schema)] = name
            self.typed_dict(name, schema)
        else:
            expr = self.annotation(schema, name)
            lines = [f"{name}: TypeAlias = {expr}"]
            if schema.get("description"):
                lines += docstring(schema["description"], "")
            self.blocks.append("\n".join(lines))
        self.exported.append(name)
        return name

    @staticmethod
    def types_of(schema: dict[str, Any]) -> list[str]:
        t = schema.get("type")
        if t is None:
            return []
        return list(t) if isinstance(t, list) else [t]

    def is_object(self, schema: dict[str, Any]) -> bool:
        types = self.types_of(schema)
        return "object" in types or (not types and "properties" in schema)

    def typed_dict(self, name: str, schema: dict[str, Any]) -> None:
        required = set(schema.get("required", []))
        fields: list[tuple[str, str]] = []
        for prop, sub in schema["properties"].items():
            ann = self.annotation(sub, name + pascal(prop))
            fields.append((prop, ann if prop in required else f"NotRequired[{ann}]"))
        functional = any(not p.isidentifier() or keyword.iskeyword(p) for p, _ in fields)
        lines: list[str] = []
        if functional:
            if schema.get("description"):
                lines += [f"# {line}" for line in textwrap.wrap(schema["description"], 96)]
            lines.append(f'{name} = TypedDict("{name}", {{')
            lines += [f'    "{p}": {a},' for p, a in fields]
            lines.append("})")
        else:
            lines.append(f"class {name}(TypedDict):")
            lines += docstring(schema.get("description", ""), "    ")
            lines += [f"    {p}: {a}" for p, a in fields]
            if not fields:
                lines.append("    pass")
        self.blocks.append("\n".join(lines))

    def variant_names(self, variants: list[dict[str, Any]], base: str) -> list[str]:
        objects = [self.resolve(v) for v in variants]
        if all(self.is_object(o) and o.get("properties") for o in objects):
            common = set.intersection(*(set(o["properties"]) for o in objects))
            for prop in sorted(common):
                values = [o["properties"][prop].get("enum") for o in objects]
                if all(v and len(v) == 1 and isinstance(v[0], str) for v in values):
                    tags = [pascal(v[0]) for v in values if v]
                    if len(set(tags)) == len(tags):
                        return [base + t for t in tags]
        return [f"{base}{i + 1}" for i in range(len(variants))]

    def resolve(self, schema: dict[str, Any]) -> dict[str, Any]:
        while "$ref" in schema:
            schema = self.schemas[schema["$ref"].rsplit("/", 1)[1]]
        return schema

    def annotation(self, schema: dict[str, Any], hint: str) -> str:
        if not schema:
            self.uses_any = True
            return "Any"
        if "$ref" in schema:
            return self.component(schema["$ref"].rsplit("/", 1)[1])
        if len(schema.get("allOf", [])) == 1:
            return self.annotation(schema["allOf"][0], hint)
        if "anyOf" in schema or "oneOf" in schema:
            variants = schema.get("anyOf") or schema["oneOf"]
            names = self.variant_names(variants, hint)
            parts: list[str] = []
            for sub, sub_name in zip(variants, names, strict=True):
                ann = self.annotation(sub, sub_name)
                for piece in ann.split(" | "):
                    if piece not in parts:
                        parts.append(piece)
            if "None" in parts:
                parts.remove("None")
                parts.append("None")
            return " | ".join(parts)
        types = self.types_of(schema)
        nullable = "null" in types
        types = [t for t in types if t != "null"]
        if "enum" in schema:
            values = schema["enum"]
            literal = [repr(v) for v in values if v is not None]
            nullable = nullable or None in values
            expr = f"Literal[{', '.join(literal)}]" if literal else "None"
            return f"{expr} | None" if nullable and literal else expr
        if not types:
            types = ["object"] if "properties" in schema else []
        if not types and nullable:
            return "None"
        if not types:
            self.uses_any = True
            return "Any | None" if nullable else "Any"
        parts = [self.single(t, schema, hint) for t in types]
        if nullable:
            parts.append("None")
        return " | ".join(parts)

    def single(self, kind: str, schema: dict[str, Any], hint: str) -> str:
        if kind == "string":
            if schema.get("format") == "binary":
                return "FileUpload"
            if schema.get("description", "").startswith("JSON-encoded"):
                self.uses_any = True
                return "JsonText"
            return "str"
        if kind == "integer":
            return "int"
        if kind == "number":
            return "float"
        if kind == "boolean":
            return "bool"
        if kind == "array":
            return f"list[{self.annotation(schema.get('items', {}), hint + 'Item')}]"
        if kind == "object":
            if schema.get("properties"):
                if id(schema) in self.memo:
                    return self.memo[id(schema)]
                name = self.unique(hint)
                self.memo[id(schema)] = name
                self.typed_dict(name, schema)
                self.exported.append(name)
                return name
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                return f"dict[str, {self.annotation(extra, hint + 'Value')}]"
            self.uses_any = True
            return "dict[str, Any]"
        raise ValueError(f"unsupported schema type {kind!r} at {hint}")

    def render(self) -> str:
        imports = ["IO", "Literal", "NotRequired", "TypeAlias", "TypedDict"]
        if self.uses_any:
            imports.insert(0, "Any")
        out = [
            HEADER,
            '"""Request and response types of the BillionSend API.\n\n'
            "Every type is a ``TypedDict`` (or an alias of one): responses are plain ``dict``\n"
            'objects and request parameters are written as ``dict`` literals."""\n',
            "from __future__ import annotations\n",
            f"from typing import {', '.join(imports)}\n",
            "__all__ = ["
            + ", ".join(f'"{n}"' for n in sorted({*self.exported, "FileUpload", "JsonText"}))
            + "]\n",
            FILE_UPLOAD,
            JSON_TEXT,
        ]
        out += [block + "\n" for block in self.blocks]
        return "\n\n".join(out)


# ---------------------------------------------------------------------- operations


@dataclass
class Param:
    name: str  # wire name
    py: str  # python name
    ann: str
    required: bool
    where: str  # path | query | header
    array: bool = False


@dataclass
class Operation:
    method: str
    path: str
    resource: str
    name: str
    summary: str
    description: str
    path_params: list[Param] = field(default_factory=list)
    query_params: list[Param] = field(default_factory=list)
    header_params: list[Param] = field(default_factory=list)
    body_type: str | None = None
    body_required: bool = False
    body_omit_when_none: bool = False
    body_form: bool = False
    returns: str = "dict[str, Any]"
    stream: bool = False
    idempotency_key: bool = False
    page_item: str | None = None
    page_type: str | None = None


def build_operations(spec: dict[str, Any], types: TypeGen) -> list[Operation]:
    found = {
        (m.upper(), p): op
        for p, item in spec["paths"].items()
        for m, op in item.items()
        if m in HTTP_METHODS
    }
    ids = [op.get("operationId") for op in found.values()]
    if None in ids or len(set(ids)) != len(ids):
        raise SystemExit("every operation needs an operationId, each one different")

    ops: list[Operation] = []
    for (method, path), op in found.items():
        *group, last = op["operationId"].split(".")
        resource, name = ".".join(snake(g) for g in group), snake(last)
        hint = pascal(resource.split(".")[-1]) + pascal(name)
        params = op.get("parameters", [])
        o = Operation(
            method=method,
            path=path,
            resource=resource,
            name=name,
            summary=op.get("summary", ""),
            description=op.get("description", ""),
            idempotency_key=any(
                p["in"] == "header" and p["name"].lower() == IDEMPOTENCY_KEY_HEADER for p in params
            ),
        )
        for p in params:
            schema = p.get("schema", {})
            where = p["in"]
            if where == "header" and p["name"].lower() == IDEMPOTENCY_KEY_HEADER:
                continue
            if where == "path":
                py = pyname(p["name"])
            elif where == "header":
                py = HEADER_KWARGS.get(p["name"].lower()) or pyname(p["name"].removeprefix("x-"))
            else:
                py = pyname(p["name"])
            ann = types.annotation(schema, hint + pascal(p["name"]))
            if where == "query" and schema.get("enum") == ["true", "false"]:
                ann = 'bool | Literal["true", "false"]'
            ann = ann.replace(" | None", "")
            param = Param(
                p["name"],
                py,
                ann,
                bool(p.get("required")),
                where,
                array="array" in TypeGen.types_of(schema),
            )
            {"path": o.path_params, "query": o.query_params, "header": o.header_params}[
                where
            ].append(param)
        order = re.findall(r"{(\w+)}", path)
        o.path_params.sort(key=lambda prm: order.index(prm.name))
        if [prm.name for prm in o.path_params] != order:
            raise SystemExit(f"{method} {path}: path parameters do not match the template")

        body = op.get("requestBody")
        if body:
            content = body["content"]
            if "application/json" not in content:
                if list(content) != ["multipart/form-data"]:
                    raise SystemExit(f"{method} {path}: unsupported request body {list(content)}")
                o.body_form = True
            schema = (content.get("application/json") or content["multipart/form-data"])["schema"]
            o.body_type = types.annotation(schema, hint + "Params")
            resolved = types.resolve(schema)
            o.body_required = bool(body.get("required")) or bool(
                resolved.get("required") or "array" in TypeGen.types_of(resolved)
            )
            o.body_omit_when_none = body.get("required") is False

        success = [
            (code, resp) for code, resp in sorted(op["responses"].items()) if code.startswith("2")
        ]
        if any("text/event-stream" in r.get("content", {}) for _, r in success):
            o.stream = True
        else:
            returns: list[str] = []
            for _, resp in success:
                schema = resp.get("content", {}).get("application/json", {}).get("schema")
                if schema is None:
                    continue
                if "$ref" in schema:
                    ann = types.annotation(schema, hint + "Response")
                else:
                    ann = types.named(hint + "Response", schema)
                if ann not in returns:
                    returns.append(ann)
            if returns:
                o.returns = " | ".join(returns)
            else:
                types.uses_any = True

            # Cursor pagination: after/before and a {data, has_more} page of items with ids.
            query_names = {prm.name for prm in o.query_params}
            if {"after", "before"} <= query_names and len(returns) == 1:
                page = types.resolve(success[0][1]["content"]["application/json"]["schema"])
                props = page.get("properties", {})
                items = types.resolve(props.get("data", {}).get("items", {}))
                if "has_more" in props and has_id(types, items):
                    o.page_type = returns[0]
                    o.page_item = types.annotation(
                        props["data"]["items"], returns[0] + "DataItem"
                    ).split(" | ")[0]
        ops.append(o)
    return ops


def has_id(types: Any, schema: dict[str, Any]) -> bool:
    """Whether every shape an item can take has an ``id`` (the cursor of the next page)."""
    branches = schema.get("anyOf") or schema.get("oneOf")
    if branches:
        return all(has_id(types, types.resolve(b)) for b in branches)
    return "id" in schema.get("properties", {})


# ----------------------------------------------------------------------- resources


def class_name(resource: str, is_async: bool) -> str:
    base = "".join(pascal(part) for part in resource.split(".")) + "Resource"
    return ("Async" if is_async else "") + base


def render_resources(ops: list[Operation], is_async: bool, type_names: set[str]) -> str:
    # An operation named like a child resource (``emails.metrics`` next to
    # ``emails.metrics.clients``) becomes the call of that child resource:
    # ``client.emails.metrics(...)`` and ``client.emails.metrics.clients(...)``.
    resources = {op.resource for op in ops}
    for op in ops:
        if f"{op.resource}.{op.name}" in resources:
            op.resource, op.name = f"{op.resource}.{op.name}", "__call__"
    by_resource: dict[str, list[Operation]] = {}
    for op in ops:
        by_resource.setdefault(op.resource, []).append(op)
    # Make sure every parent resource exists, even one without its own operations.
    for resource in list(by_resource):
        parts = resource.split(".")
        for i in range(1, len(parts)):
            by_resource.setdefault(".".join(parts[:i]), [])

    used: set[str] = set()
    for op in ops:
        for text in [op.returns, op.body_type or "", op.page_item or ""] + [
            p.ann for p in op.path_params + op.query_params + op.header_params
        ]:
            used |= {t for t in re.findall(r"\b[A-Z]\w+\b", text) if t in type_names}

    aw = "await " if is_async else ""
    client_type = "AsyncAPIClient" if is_async else "SyncAPIClient"
    lines = [
        HEADER,
        '"""' + ("Async" if is_async else "Sync") + ' resources of the BillionSend client."""\n',
        "from __future__ import annotations\n",
        "from collections.abc import "
        + ("AsyncIterator" if is_async else "Iterator")
        + ", Mapping, Sequence",
        "from typing import Any, Literal, cast\n",
        "import httpx\n",
        f"from .._base_client import {client_type}, encode_path",
        "from .._pagination import " + ("apaginate" if is_async else "paginate"),
        "from .._streaming import " + ("AsyncEventStream" if is_async else "EventStream"),
    ]
    if used:
        lines.append("from ..types import (")
        lines += [f"    {n}," for n in sorted(used)]
        lines.append(")")
    lines.append("")

    # Children first so parents can refer to them.
    for resource in sorted(by_resource, key=lambda r: (-r.count("."), r)):
        cls = class_name(resource, is_async)
        children = sorted(r for r in by_resource if r.rsplit(".", 1)[0] == resource and "." in r)
        lines.append(f"\nclass {cls}:")
        title = resource.replace(".", " ").replace("_", " ")
        lines.append(f'    """Operations on {title}."""\n')
        lines.append(f"    def __init__(self, client: {client_type}) -> None:")
        lines.append("        self._client = client")
        for child in children:
            attr = child.rsplit(".", 1)[1]
            lines.append(f"        self.{attr} = {class_name(child, is_async)}(client)")
        for op in by_resource[resource]:
            lines.append("")
            lines += render_method(op, is_async, aw)
            if op.page_item:
                lines.append("")
                lines += render_paginator(op, is_async)
    lines.append("")
    lines.append("__all__ = [")
    lines += [f'    "{class_name(r, is_async)}",' for r in sorted(by_resource)]
    lines.append("]")
    return "\n".join(lines) + "\n"


def signature(op: Operation, *, paginator: bool = False) -> list[str]:
    args = ["self"]
    args += [f"{p.py}: str" for p in op.path_params]
    if op.body_type and not paginator:
        args.append(
            f"params: {op.body_type}"
            if op.body_required
            else f"params: {op.body_type} | None = None"
        )
    kw: list[str] = []
    for p in op.query_params:
        ann = p.ann
        if op.stream and p.name == "types":
            ann = "str | Sequence[str]"
        if p.array:
            ann = ann.replace("list[", "Sequence[", 1)
        kw.append(f"{p.py}: {ann}" if p.required else f"{p.py}: {ann} | None = None")
    for p in op.header_params:
        kw.append(f"{p.py}: {p.ann}" if p.required else f"{p.py}: {p.ann} | None = None")
    if op.idempotency_key:
        kw.append("idempotency_key: str | None = None")
    if op.stream:
        kw.append("max_reconnects: int = 5")
    kw.append("extra_headers: Mapping[str, str] | None = None")
    kw.append("timeout: float | httpx.Timeout | None = None")
    return [*args, "*", *kw]


def call_kwargs(op: Operation, *, after: str = "after", before: str = "before") -> list[str]:
    kwargs: list[str] = []
    query = []
    for p in op.query_params:
        value = p.py
        if op.stream and p.name == "last_event_id":
            continue
        if op.stream and p.name == "types":
            value = f"{p.py} if {p.py} is None or isinstance({p.py}, str) else ','.join({p.py})"
        if p.name == "after":
            value = after
        if p.name == "before":
            value = before
        query.append(f'"{p.name}": {value}')
    if query:
        kwargs.append("query={" + ", ".join(query) + "}")
    if op.header_params:
        kwargs.append(
            "headers={" + ", ".join(f'"{p.name}": {p.py}' for p in op.header_params) + "}"
        )
    return kwargs


def path_expr(op: Operation) -> str:
    expr = op.path
    for p in op.path_params:
        expr = expr.replace("{" + p.name + "}", "{encode_path(" + p.py + ")}")
    return f'f"{expr}"' if op.path_params else f'"{expr}"'


def render_method(op: Operation, is_async: bool, aw: str) -> list[str]:
    sig = signature(op)
    stream_cls = "AsyncEventStream" if is_async else "EventStream"
    returns = stream_cls if op.stream else op.returns
    head = "async def" if is_async else "def"
    lines = [f"    {head} {op.name}(", *[f"        {a}," for a in sig], f"    ) -> {returns}:"]
    doc = op.summary.rstrip(".") + "." if op.summary else ""
    if op.description:
        doc += "\n\n" + op.description
    if op.idempotency_key:
        doc += (
            "\n\nSent with an ``Idempotency-Key``: ``idempotency_key`` when given, else"
            " one made up for this call, so that its retries never send twice."
        )
    doc += f"\n\n``{op.method} {op.path}``"
    lines += docstring(doc, "        ")
    kwargs = call_kwargs(op)
    if op.stream:
        call = [
            f"{path_expr(op)}",
            *kwargs,
            "last_event_id=last_event_id",
            "max_reconnects=max_reconnects",
            "extra_headers=extra_headers",
            "timeout=timeout",
        ]
        lines.append(f"        return {aw}self._client.stream_events(")
        lines += [f"            {c}," for c in call]
        lines.append("        )")
        return lines
    call = [f'"{op.method}"', path_expr(op), *kwargs]
    if op.body_type:
        if op.body_form:
            call.append("form=params")
        elif op.body_required or op.body_omit_when_none:
            call.append("body=params")
        else:
            call.append("body={} if params is None else params")
    if op.idempotency_key:
        call += ["idempotency_key=idempotency_key", "auto_idempotency_key=True"]
    if op.path == "/agent/signup":
        call.append("auth=False")
    call += ["extra_headers=extra_headers", "timeout=timeout"]
    lines.append(f"        response = {aw}self._client.request(")
    lines += [f"            {c}," for c in call]
    lines.append("        )")
    lines.append(f'        return cast("{op.returns}", response)')
    return lines


def render_paginator(op: Operation, is_async: bool) -> list[str]:
    sig = signature(op, paginator=True)
    item = op.page_item
    it = "AsyncIterator" if is_async else "Iterator"
    head = "def"
    name = f"{op.name}_all"
    lines = [f"    {head} {name}(", *[f"        {a}," for a in sig], f"    ) -> {it}[{item}]:"]
    lines += docstring(
        f"Iterate over every item of :meth:`{op.name}`, fetching pages as needed.\n\n"
        "Walks in the list's own order, from ``after`` (or the first page) on; pass "
        "``before`` instead to walk the other way.",
        "        ",
    )
    args = [p.py for p in op.path_params]
    passthrough = [
        f"{p.py}={p.py}" for p in op.query_params if p.name not in {"after", "before"}
    ] + [f"{p.py}={p.py}" for p in op.header_params]
    passthrough += [
        "after=after_",
        "before=before_",
        "extra_headers=extra_headers",
        "timeout=timeout",
    ]
    inner_head = "async def" if is_async else "def"
    aw = "await " if is_async else ""
    lines.append(f"        {inner_head} fetch(after_: str | None, before_: str | None) -> object:")
    lines.append(f"            return {aw}self.{op.name}(")
    lines += [f"                {a}," for a in args + passthrough]
    lines.append("            )")
    lines.append("")
    fn = "apaginate" if is_async else "paginate"
    kind = "AsyncIterator" if is_async else "Iterator"
    lines.append(f'        return cast("{kind}[{item}]", {fn}(fetch, after=after, before=before))')
    return lines


