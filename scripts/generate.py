"""Generate the typed surface of the SDK from the OpenAPI snapshot.

Writes three modules, all derived from ``openapi/api.openapi.json``:

* ``src/billionsend/types.py``: a ``TypedDict`` (or alias) for every schema
  the operations use, request bodies and responses alike;
* ``src/billionsend/resources/_sync.py`` and ``_async.py``: one method per
  operation, grouped into resources, identical for the sync and async clients.

Each operation's method is named by its ``operationId``: the dotted path of
the method, segments in camelCase (``emails.receiving.attachments.list`` is
``client.emails.receiving.attachments.list``), written here in snake_case.

Usage::

    python scripts/generate.py          # rewrite the generated modules
    python scripts/generate.py --check  # fail if they differ from the snapshot
"""

from __future__ import annotations

